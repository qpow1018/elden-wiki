create temp view ash_of_war_seed_skills as
select s.name as ash_name, k.id as skill_id
from ash_of_war_seed s
join public.weapon_skills k on k.name = s.skill_name
  and (s.skill_name not in ('회전 베기', '돌아라 돌아라') or k.fp_cost_text = s.skill_fp);

insert into public.weapon_skills (name, description, fp_cost_text)
select s.skill_name, s.skill_description, s.skill_fp
from ash_of_war_seed s
where s.skill_name is not null
  and not exists (select 1 from ash_of_war_seed_skills k where k.ash_name = s.name);

do $$
begin
  if exists (
    select s.name from ash_of_war_seed s
    left join ash_of_war_seed_skills k on k.ash_name = s.name
    where s.skill_name is not null
    group by s.name having count(k.skill_id) <> 1
  ) then
    raise exception '전회별 전투 기술을 하나로 연결해야 합니다.';
  end if;
end;
$$;

update public.weapon_skills k
set description = s.skill_description, fp_cost_text = s.skill_fp
from ash_of_war_seed s
join ash_of_war_seed_skills link on link.ash_name = s.name
where k.id = link.skill_id
  and (k.description, k.fp_cost_text) is distinct from (s.skill_description, s.skill_fp);

with categorized as (
  select s.*, (
    select c.id from public.game_item_categories c
    where c.type = 'ash_of_war' and c.name = s.category_name
  ) as category_id
  from ash_of_war_seed s
), moved as (
  update public.game_items i
  set category_id = s.category_id, sort_order = s.sort_order, game_description = s.game_description
  from categorized s
  where i.type = 'ash_of_war' and i.name = s.name and i.content_code = s.content_code
    and (i.category_id, i.sort_order, i.game_description)
      is distinct from (s.category_id, s.sort_order, s.game_description)
)
insert into public.game_items (name, type, category_id, sort_order, content_code, game_description)
select s.name, 'ash_of_war', s.category_id, s.sort_order, s.content_code, s.game_description
from categorized s
where not exists (
  select 1 from public.game_items i
  where i.type = 'ash_of_war' and i.name = s.name and i.content_code = s.content_code
);

delete from public.game_item_categories
where type = 'ash_of_war' and name = '전회';

insert into public.ash_of_war_details (game_item_id, skill_id, native_affinity, applicable_armaments_text)
select i.id, k.skill_id, s.native_affinity, s.applicable_armaments_text
from ash_of_war_seed s
join public.game_items i on i.type = 'ash_of_war' and i.name = s.name and i.content_code = s.content_code
left join ash_of_war_seed_skills k on k.ash_name = s.name
on conflict (game_item_id) do update
set skill_id = excluded.skill_id,
    native_affinity = excluded.native_affinity,
    applicable_armaments_text = excluded.applicable_armaments_text;

