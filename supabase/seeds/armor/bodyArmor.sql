  and (i.sort_order, i.game_description) is distinct from (s.sort_order, s.game_description);

insert into public.game_items (name, type, category_id, sort_order, content_code, game_description)
select s.name, 'armor', c.id, s.sort_order, s.content_code, s.game_description
from body_armor_seed s join public.game_item_categories c on c.type = 'armor' and c.name = '갑옷'
