from source s
join public.game_item_categories c on c.type = 'other' and c.name = s.category
where not exists (
  select 1
  from public.game_items i
  where i.category_id = c.id and i.name = s.name and i.content_code = s.content_code
    and i.sort_order = s.sort_order
)
